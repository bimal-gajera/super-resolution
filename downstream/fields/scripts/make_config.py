#!/usr/bin/env python3
"""Training config for one flow: the paper's PRUE+ config with only data location, countries, run length and
logging changed (model, loss, augmentations, crop size and learning rate stay exactly as published).

    python scripts/make_config.py --name check_sr03_b3 --root data/ftp_layout/check_sr03 --epochs 50 \
        --countries belgium lithuania latvia croatia cambodia south_africa

Writes configs/<name>.yaml; runs go to runs/<name>/ (checkpoints, CSV log). Train with the paper's launcher:
    ../../../envs/ftp/bin/ftw model fit -c configs/<name>.yaml
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PAPER = ROOT / "third_party/fields-of-the-planet/configs"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True)
    ap.add_argument("--root", type=Path, required=True, help="a folder written by scripts/make_ftp_layout.py")
    ap.add_argument("--backbone", default="b3", choices=("b3", "b7"))
    ap.add_argument("--countries", nargs="+", required=True)
    ap.add_argument("--val-countries", nargs="+", default=None, help="default: --countries")
    ap.add_argument("--epochs", type=int, default=None, help="default: the paper's (100)")
    ap.add_argument("--batch-size", type=int, default=None, help="default: the paper's (32 for B3, 8 for B7)")
    ap.add_argument("--num-workers", type=int, default=8)
    ap.add_argument("--precision", default=None, help="default: the paper's (bf16-mixed; use 16-mixed on a V100)")
    ap.add_argument("--wandb-project", default=None, help="also log to this W&B project (run name = --name)")
    args = ap.parse_args()

    cfg = yaml.safe_load((PAPER / f"ftw_planet_efnet{args.backbone[1]}_512_prueplus.yaml").read_text())
    run = ROOT / "runs" / args.name
    trainer = cfg["trainer"]
    trainer["default_root_dir"] = str(run)
    trainer["logger"] = [{"class_path": "lightning.pytorch.loggers.CSVLogger",
                          "init_args": {"save_dir": str(run), "name": "log"}}]
    if args.wandb_project:      # the paper's config logs to W&B too (its own entity / project)
        trainer["logger"].append({"class_path": "lightning.pytorch.loggers.WandbLogger",
                                  "init_args": {"project": args.wandb_project, "name": args.name, "id": args.name,
                                                "resume": "allow", "save_dir": str(run), "log_model": False}})
    for cb in trainer["callbacks"]:
        if cb["class_path"].endswith("ModelCheckpoint"):
            cb["init_args"]["dirpath"] = str(run / "checkpoints")
    if args.epochs:
        trainer["max_epochs"] = args.epochs
    if args.precision:
        trainer["precision"] = args.precision
    data = cfg["data"]["init_args"]
    data["train_countries"] = data["test_countries"] = list(args.countries)
    data["val_countries"] = list(args.val_countries or args.countries)
    data["num_workers"] = args.num_workers
    if args.batch_size:
        data["batch_size"] = args.batch_size
    root = args.root if args.root.is_absolute() else ROOT / args.root
    cfg["data"]["dict_kwargs"]["root"] = str(root)

    out = ROOT / "configs" / f"{args.name}.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(f"# generated by scripts/make_config.py from the paper's "
                   f"ftw_planet_efnet{args.backbone[1]}_512_prueplus.yaml\n" + yaml.safe_dump(cfg, sort_keys=False))
    print(f"-> {out}")


if __name__ == "__main__":
    main()
